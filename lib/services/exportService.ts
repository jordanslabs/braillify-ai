import type { ExportResult } from "@/lib/types";

/**
 * Copy text to clipboard
 */
export async function copyToClipboard(text: string): Promise<ExportResult> {
  if (!text.trim()) {
    return { success: false, format: "text", error: "Tidak ada teks untuk disalin" };
  }
  try {
    await navigator.clipboard.writeText(text);
    return { success: true, format: "text" };
  } catch {
    // Fallback
    try {
      const textarea = document.createElement("textarea");
      textarea.value = text;
      textarea.style.position = "fixed";
      textarea.style.opacity = "0";
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand("copy");
      document.body.removeChild(textarea);
      return { success: true, format: "text" };
    } catch {
      return { success: false, format: "text", error: "Gagal menyalin teks" };
    }
  }
}

/**
 * Export result as an image (PNG)
 */
export async function exportAsImage(
  content: string,
  brailleUnicode: string,
  filename = "braillify-result"
): Promise<ExportResult> {
  if (!content.trim() && !brailleUnicode.trim()) {
    return { success: false, format: "image", error: "Tidak ada konten untuk diekspor" };
  }

  try {
    const canvas = document.createElement("canvas");
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("Canvas not supported");

    const padding = 40;
    const width = 600;
    const lineHeight = 28;

    // Measure content
    ctx.font = "16px monospace";
    const lines = content.split("\n");
    const brailleLines = brailleUnicode ? brailleUnicode.match(/.{1,30}/g) ?? [brailleUnicode] : [];
    const totalLines = lines.length + (brailleLines.length > 0 ? brailleLines.length + 2 : 0);
    const height = padding * 2 + 80 + totalLines * lineHeight + 60;

    canvas.width = width;
    canvas.height = height;

    // Background
    ctx.fillStyle = "#09111F";
    ctx.fillRect(0, 0, width, height);

    // Header
    ctx.fillStyle = "#2563EB";
    ctx.font = "bold 20px system-ui, sans-serif";
    ctx.fillText("Braillify-AI", padding, padding + 24);

    ctx.fillStyle = "#64748B";
    ctx.font = "12px system-ui, sans-serif";
    ctx.fillText(
      `Diekspor: ${new Date().toLocaleDateString("id-ID", { dateStyle: "long" })}`,
      padding,
      padding + 44
    );

    // Separator
    ctx.strokeStyle = "#26354B";
    ctx.lineWidth = 1;
    ctx.beginPath();
    ctx.moveTo(padding, padding + 60);
    ctx.lineTo(width - padding, padding + 60);
    ctx.stroke();

    // Latin text
    let y = padding + 90;
    ctx.fillStyle = "#94A3B8";
    ctx.font = "bold 11px system-ui, sans-serif";
    ctx.fillText("TEKS LATIN", padding, y);
    y += 24;

    ctx.fillStyle = "#F8FAFC";
    ctx.font = "15px system-ui, sans-serif";
    for (const line of lines) {
      ctx.fillText(line, padding, y);
      y += lineHeight;
    }

    // Braille text
    if (brailleLines.length > 0) {
      y += 16;
      ctx.fillStyle = "#94A3B8";
      ctx.font = "bold 11px system-ui, sans-serif";
      ctx.fillText("BRAILLE", padding, y);
      y += 24;

      ctx.fillStyle = "#C4B5FD";
      ctx.font = "18px monospace";
      for (const line of brailleLines) {
        ctx.fillText(line, padding, y);
        y += lineHeight;
      }
    }

    // Watermark
    ctx.fillStyle = "#26354B";
    ctx.font = "10px system-ui, sans-serif";
    ctx.fillText("Generated by Braillify-AI • Offline Braille Translator", padding, height - 20);

    // Download
    const blob = await new Promise<Blob>((resolve, reject) => {
      canvas.toBlob(
        (b) => (b ? resolve(b) : reject(new Error("Canvas export failed"))),
        "image/png"
      );
    });

    const fullFilename = `${filename}.png`;
    downloadBlob(blob, fullFilename);

    return { success: true, format: "image", filename: fullFilename };
  } catch (err) {
    return {
      success: false,
      format: "image",
      error: `Gagal mengekspor gambar: ${err instanceof Error ? err.message : "Unknown error"}`,
    };
  }
}

/**
 * Export result as a simple PDF (using canvas-based approach)
 */
export async function exportAsPdf(
  content: string,
  brailleUnicode: string,
  filename = "braillify-result"
): Promise<ExportResult> {
  if (!content.trim() && !brailleUnicode.trim()) {
    return { success: false, format: "pdf", error: "Tidak ada konten untuk diekspor" };
  }

  try {
    const canvas = document.createElement("canvas");
    const width = 840;
    const padding = 64;
    const lineHeight = 32;
    canvas.width = width;
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("Canvas not supported");

    const bodyFont = "18px system-ui, sans-serif";
    const brailleFont = "24px 'Segoe UI Symbol', 'Noto Sans Symbols 2', sans-serif";
    const wrap = (text: string, font: string): string[] => {
      ctx.font = font;
      const wrapped: string[] = [];
      for (const paragraph of text.split(/\r?\n/)) {
        if (!paragraph) {
          wrapped.push("");
          continue;
        }
        let line = "";
        for (const word of paragraph.split(/\s+/)) {
          const candidate = line ? `${line} ${word}` : word;
          if (ctx.measureText(candidate).width <= width - padding * 2) {
            line = candidate;
            continue;
          }
          if (line) wrapped.push(line);
          if (ctx.measureText(word).width <= width - padding * 2) {
            line = word;
            continue;
          }
          line = "";
          for (const char of word) {
            if (ctx.measureText(line + char).width > width - padding * 2 && line) {
              wrapped.push(line);
              line = char;
            } else {
              line += char;
            }
          }
        }
        if (line) wrapped.push(line);
      }
      return wrapped;
    };

    const textLines = wrap(content, bodyFont);
    const brailleLines = brailleUnicode ? wrap(brailleUnicode, brailleFont) : [];
    const headerHeight = 214;
    const sectionHeadingHeight = 40;
    const sectionGap = 32;
    const footerHeight = 72;
    const height =
      padding * 2 +
      headerHeight +
      sectionHeadingHeight +
      textLines.length * lineHeight +
      (brailleLines.length
        ? sectionGap + sectionHeadingHeight + brailleLines.length * lineHeight
        : 0) +
      footerHeight;

    canvas.height = height;
    ctx.fillStyle = "#F0F2FA";
    ctx.fillRect(0, 0, width, height);
    ctx.fillStyle = "#FFFFFF";
    ctx.beginPath();
    ctx.roundRect(28, 28, width - 56, height - 56, 24);
    ctx.fill();

    let y = padding + 16;
    ctx.fillStyle = "#6C63FF";
    ctx.font = "bold 30px system-ui, sans-serif";
    ctx.fillText("Braillify-AI", padding, y);
    y += 36;
    ctx.fillStyle = "#777894";
    ctx.font = "14px system-ui, sans-serif";
    ctx.fillText(
      `Hasil terjemahan · ${new Date().toLocaleDateString("id-ID", { dateStyle: "long" })}`,
      padding,
      y
    );
    y += 31;
    ctx.strokeStyle = "#E3E5F0";
    ctx.lineWidth = 1;
    ctx.beginPath();
    ctx.moveTo(padding, y);
    ctx.lineTo(width - padding, y);
    ctx.stroke();
    y += 42;

    const drawSection = (label: string, lines: string[], font: string, color: string) => {
      ctx.fillStyle = "#8B8CA7";
      ctx.font = "bold 12px system-ui, sans-serif";
      ctx.fillText(label, padding, y);
      y += sectionHeadingHeight - 10;
      ctx.fillStyle = color;
      ctx.font = font;
      for (const line of lines) {
        if (line) ctx.fillText(line, padding, y);
        y += lineHeight;
      }
    };

    drawSection("TEKS LATIN", textLines, bodyFont, "#252644");
    if (brailleLines.length) {
      y += sectionGap;
      drawSection("BRAILLE", brailleLines, brailleFont, "#5146A5");
    }
    ctx.fillStyle = "#A0A1B5";
    ctx.font = "11px system-ui, sans-serif";
    ctx.fillText("Generated by Braillify-AI · pemrosesan lokal", padding, height - padding);

    const jpeg = await new Promise<Blob>((resolve, reject) => {
      canvas.toBlob(
        (blob) => (blob ? resolve(blob) : reject(new Error("PDF image rendering failed"))),
        "image/jpeg",
        0.94
      );
    });
    const imageBytes = new Uint8Array(await jpeg.arrayBuffer());
    const encoder = new TextEncoder();
    const chunks: Uint8Array[] = [];
    let byteLength = 0;
    const append = (chunk: string | Uint8Array) => {
      const bytes = typeof chunk === "string" ? encoder.encode(chunk) : chunk;
      chunks.push(bytes);
      byteLength += bytes.length;
    };
    const offsets = [0];
    const pageWidth = 595;
    const pageHeight = Math.ceil((pageWidth * canvas.height) / canvas.width);

    append("%PDF-1.4\n");
    offsets.push(byteLength);
    append("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n");
    offsets.push(byteLength);
    append("2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n");
    offsets.push(byteLength);
    append(
      `3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /XObject << /Im0 4 0 R >> >> /Contents 5 0 R >>\nendobj\n`
    );
    offsets.push(byteLength);
    append(
      `4 0 obj\n<< /Type /XObject /Subtype /Image /Width ${canvas.width} /Height ${canvas.height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${imageBytes.length} >>\nstream\n`
    );
    append(imageBytes);
    append("\nendstream\nendobj\n");
    offsets.push(byteLength);
    const pageContent = `q\n${pageWidth} 0 0 ${pageHeight} 0 0 cm\n/Im0 Do\nQ\n`;
    append(
      `5 0 obj\n<< /Length ${encoder.encode(pageContent).length} >>\nstream\n${pageContent}endstream\nendobj\n`
    );

    const xrefOffset = byteLength;
    let xref = "xref\n0 6\n0000000000 65535 f \n";
    for (const offset of offsets.slice(1)) {
      xref += `${String(offset).padStart(10, "0")} 00000 n \n`;
    }
    xref += `trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
    append(xref);

    const pdfBytes = new Uint8Array(byteLength);
    let position = 0;
    for (const chunk of chunks) {
      pdfBytes.set(chunk, position);
      position += chunk.length;
    }

    const blob = new Blob([pdfBytes], { type: "application/pdf" });
    const fullFilename = `${filename}.pdf`;
    downloadBlob(blob, fullFilename);

    return { success: true, format: "pdf", filename: fullFilename };
  } catch (err) {
    return {
      success: false,
      format: "pdf",
      error: `Gagal mengekspor: ${err instanceof Error ? err.message : "Unknown error"}`,
    };
  }
}

/**
 * Share content using Web Share API
 */
export async function shareContent(
  title: string,
  text: string,
  brailleUnicode?: string
): Promise<ExportResult> {
  const shareText = brailleUnicode
    ? `${text}\n\nBraille: ${brailleUnicode}`
    : text;

  if (navigator.share) {
    try {
      await navigator.share({
        title: `Braillify-AI — ${title}`,
        text: shareText,
      });
      return { success: true, format: "text" };
    } catch (err) {
      if (err instanceof Error && err.name === "AbortError") {
        return { success: false, format: "text", error: "Berbagi dibatalkan" };
      }
      return { success: false, format: "text", error: "Gagal berbagi" };
    }
  }

  // Fallback to clipboard
  return copyToClipboard(shareText);
}

/* ── Utility ── */
function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.style.display = "none";
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }, 100);
}
